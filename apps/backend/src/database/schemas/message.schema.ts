import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { Document, Schema as MongooseSchema } from 'mongoose';

export type MessageDocument = Message & Document;

@Schema({ timestamps: true })
export class Message {
  @Prop({ required: true, type: MongooseSchema.Types.ObjectId, ref: 'Workspace', index: true })
  workspaceId: MongooseSchema.Types.ObjectId | string;

  @Prop({ required: true, type: MongooseSchema.Types.ObjectId, ref: 'Conversation', index: true })
  conversationId: MongooseSchema.Types.ObjectId | string;

  @Prop({ required: true, unique: true, index: true, trim: true })
  waMessageId: string; // The unique message identifier returned/sent by Meta Cloud API

  @Prop({ required: true, enum: ['inbound', 'outbound'] })
  direction: string;

  @Prop({ required: true, enum: ['text', 'image', 'audio', 'video', 'document', 'template'], default: 'text' })
  type: string;

  @Prop({ required: true, enum: ['sent', 'delivered', 'read', 'failed'], default: 'sent' })
  status: string;

  @Prop({ type: String, trim: true, default: null })
  body: string | null;

  @Prop({ type: String, trim: true, default: null })
  mediaUrl: string | null; // Location on Utho S3 object storage or Meta CDN URL

  @Prop({ type: String, trim: true, default: null })
  transcript: string | null; // Whisper speech-to-text transcript

  @Prop({ type: [String], default: [] })
  aiSuggestions: string[]; // List of AI suggested replies generated by Claude
}

export const MessageSchema = SchemaFactory.createForClass(Message);

// Compound index to speed up message retrieval inside active conversation windows
MessageSchema.index({ workspaceId: 1, conversationId: 1, createdAt: 1 });
